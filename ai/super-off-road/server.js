// Super Off Road Remix standalone server. Zero dependencies.
//   node server.js            -> http://localhost:8766   (PORT=1234 node server.js to change; NO_OPEN=1 to skip opening a browser)
// Serves the game files and runs a built-in matchmaking broker at /peerjs, so online play (host code / join code)
// works without the public PeerJS service. Races themselves run peer to peer over WebRTC, exactly as before.
const http = require('http'), crypto = require('crypto'), fs = require('fs'), path = require('path'), os = require('os'), { exec } = require('child_process');
const PORT = +process.env.PORT || 8766, ROOT = __dirname, MAX_MSG = 65536;
const GUID = '258EAFA5-E914-47DA-95CA-C5AB0DC85B11';
const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.json': 'application/json', '.png': 'image/png', '.svg': 'image/svg+xml', '.ico': 'image/x-icon' };

const CONFIG_JS = `// Generated by server.js: use this server's built-in matchmaking broker.
window.SOR_BROKER = (location.protocol === 'https:' ? 'wss://' : 'ws://') + location.host + '/peerjs?key=peerjs';
`;

const server = http.createServer((req, res) => {
  let u;
  try { u = decodeURIComponent(req.url.split('?')[0]); } catch (e) { res.writeHead(400); return res.end(); }
  if (u === '/config.js') { res.writeHead(200, { 'Content-Type': TYPES['.js'], 'Cache-Control': 'no-cache' }); return res.end(CONFIG_JS); }
  if (u === '/favicon.ico') { res.writeHead(204); return res.end(); }
  if (u === '/health') { res.writeHead(200); return res.end('ok'); }
  if (u === '/') u = '/index.html';
  const file = path.normalize(path.join(ROOT, u));
  const type = TYPES[path.extname(file)];
  if (!file.startsWith(ROOT + path.sep) || !type || path.basename(file) === 'server.js') { res.writeHead(404); return res.end('Not found'); }
  fs.readFile(file, (err, data) => {
    if (err) { res.writeHead(404); return res.end('Not found'); }
    res.writeHead(200, { 'Content-Type': type, 'Cache-Control': 'no-cache' });
    res.end(data);
  });
});

// ------------------------------------------------------------------ PeerJS-compatible broker over WebSocket
// Clients connect to /peerjs?id=<peer id>; the broker answers OPEN (or ID-TAKEN) and then relays
// OFFER / ANSWER / CANDIDATE messages to the peer named in `dst`, stamping `src`.
const peers = new Map();

server.on('upgrade', (req, socket) => {
  const key = req.headers['sec-websocket-key'];
  if (!key || String(req.headers.upgrade).toLowerCase() !== 'websocket' || !req.url.startsWith('/peerjs')) return socket.destroy();
  const id = new URL(req.url, 'http://x').searchParams.get('id') || '';
  const accept = crypto.createHash('sha1').update(key + GUID).digest('base64');
  socket.write('HTTP/1.1 101 Switching Protocols\r\nUpgrade: websocket\r\nConnection: Upgrade\r\nSec-WebSocket-Accept: ' + accept + '\r\n\r\n');
  socket.setNoDelay(true);
  const c = { socket, buf: Buffer.alloc(0), id, dead: false };
  socket.on('data', d => { c.buf = Buffer.concat([c.buf, d]); parse(c); });
  socket.on('close', () => drop(c));
  socket.on('error', () => drop(c));
  if (!/^[A-Za-z0-9_-]{1,64}$/.test(id)) { sendObj(c, { type: 'ERROR', payload: { msg: 'Bad id' } }); return socket.end(); }
  if (peers.has(id)) { sendObj(c, { type: 'ID-TAKEN', payload: { msg: 'ID is taken' } }); c.id = null; return socket.end(); }
  peers.set(id, c);
  sendObj(c, { type: 'OPEN' });
});

function parse(c) {
  for (;;) {
    const b = c.buf;
    if (b.length < 2) return;
    const op = b[0] & 15, masked = !!(b[1] & 128);
    let len = b[1] & 127, off = 2;
    if (len === 126) { if (b.length < 4) return; len = b.readUInt16BE(2); off = 4; }
    else if (len === 127) { if (b.length < 10) return; len = Number(b.readBigUInt64BE(2)); off = 10; }
    if (len > MAX_MSG) return c.socket.destroy();
    const ml = masked ? 4 : 0;
    if (b.length < off + ml + len) return;
    let p = b.subarray(off + ml, off + ml + len);
    if (masked) { const m = b.subarray(off, off + 4); p = Buffer.from(p); for (let i = 0; i < p.length; i++) p[i] ^= m[i & 3]; }
    c.buf = b.subarray(off + ml + len);
    if (op === 8) return c.socket.end();
    if (op === 9) { frame(c, p, 10); continue; }
    if (op === 1) handle(c, p.toString('utf8')); // signaling messages are small; fragmented frames are not used by browsers here
  }
}

function frame(c, data, op = 1) {
  if (c.dead || c.socket.destroyed) return;
  const p = Buffer.isBuffer(data) ? data : Buffer.from(data), n = p.length;
  let h;
  if (n < 126) h = Buffer.from([128 | op, n]);
  else if (n < 65536) { h = Buffer.alloc(4); h[0] = 128 | op; h[1] = 126; h.writeUInt16BE(n, 2); }
  else { h = Buffer.alloc(10); h[0] = 128 | op; h[1] = 127; h.writeBigUInt64BE(BigInt(n), 2); }
  c.socket.write(Buffer.concat([h, p]));
}
const sendObj = (c, o) => frame(c, JSON.stringify(o));

function handle(c, text) {
  if (!c.id || peers.get(c.id) !== c) return;
  let m; try { m = JSON.parse(text); } catch (e) { return; }
  if (!m || typeof m.type !== 'string' || m.type === 'HEARTBEAT') return;
  if (typeof m.dst !== 'string') return;
  const d = peers.get(m.dst);
  if (d) sendObj(d, { type: m.type, src: c.id, dst: m.dst, payload: m.payload });
  else if (m.type === 'OFFER') sendObj(c, { type: 'EXPIRE', src: m.dst, dst: c.id, payload: { msg: 'Could not connect to peer ' + m.dst } });
}

function drop(c) {
  if (c.dead) return; c.dead = true;
  if (c.id && peers.get(c.id) === c) peers.delete(c.id);
}

// Keep idle connections alive through routers and proxies.
setInterval(() => { for (const c of peers.values()) frame(c, Buffer.alloc(0), 9); }, 25000);

// ------------------------------------------------------------------ start
server.on('error', e => {
  if (e.code === 'EADDRINUSE') console.error(`Port ${PORT} is already in use. Stop the other server, or run:  PORT=${PORT + 1} node server.js`);
  else console.error(e.message);
  process.exit(1);
});
server.listen(PORT, () => {
  const lan = Object.values(os.networkInterfaces()).flat().filter(a => a && a.family === 'IPv4' && !a.internal).map(a => a.address);
  console.log('\n  SUPER OFF ROAD REMIX is running\n');
  console.log('  On this computer:   http://localhost:' + PORT);
  for (const ip of lan) console.log('  On your network:    http://' + ip + ':' + PORT);
  console.log('\n  Online games hosted here use this server for matchmaking. Press Ctrl+C to stop.\n');
  if (!process.env.NO_OPEN) {
    const url = 'http://localhost:' + PORT, cmd = process.platform === 'darwin' ? 'open' : process.platform === 'win32' ? 'start ""' : 'xdg-open';
    exec(cmd + ' ' + url, () => {});
  }
});
